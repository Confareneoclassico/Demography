def build_solve_context(pyramid_type, fert_source, mort_evo, newborn_fem_prop,
                        fert_shift):
    """Everything constant within one optimal-control solve."""
    X0 = Song.initial_population(pyramid_type)
    F0 = X0 * Song.female_share_1978
    M0 = X0 - F0
    F0[0] = 0.0                      # the 1978 infants are generated by beta(1978)
    M0[0] = 0.0
    h = Song.fertility_pattern(fert_source, fert_shift)
    tfac = Song.mortality_factor(mort_evo)                                   # (NT,)
    e0 = Song.period_life_expectancy(mort_evo, newborn_fem_prop)              # (NT,)
    return dict(X0=X0, F0=F0, M0=M0, h=h, df=Song.death_rates_females.astype(float),
                dm=Song.death_rates_males.astype(float), tfac=tfac, e0=e0,
                p=float(newborn_fem_prop))


@njit(cache=True)
def _simulate(F0, M0, beta, h, df, dm, tfac, p, mu00):
    nt = beta.shape[0]
    na = F0.shape[0]
    X = np.empty((nt, na))
    F = F0.copy()
    M = M0.copy()
    Fn = np.empty(na)
    Mn = np.empty(na)
    for i in range(nt):
        s = 0.0
        for j in range(h.shape[0]):
            s += F[15 + j] * h[j]
        births = (1 - mu00) * beta[i] * s
        F[0] = p * births
        M[0] = (1 - p) * births
        for a in range(na):
            X[i, a] = F[a] + M[a]
        if i == nt - 1:
            break
        Fn[0] = 0.0
        Mn[0] = 0.0
        for a in range(1, na):
            Fn[a] = F[a - 1] * (1 - df[a - 1] * tfac[i])
            Mn[a] = M[a - 1] * (1 - dm[a - 1] * tfac[i])
        Fn[na - 1] += F[na - 1] * (1 - df[na - 1] * tfac[i])
        Mn[na - 1] += M[na - 1] * (1 - dm[na - 1] * tfac[i])
        for a in range(na):
            F[a] = Fn[a]
            M[a] = Mn[a]
    return X


@njit(cache=True)
def _objective(beta, F0, M0, h, df, dm, tfac, p, mu00, xstar, e0, midages, pf,
               rho0, omega0, pop_max):
    X = _simulate(F0, M0, beta, h, df, dm, tfac, p, mu00)
    nt, na = X.shape
    J = 0.0
    pen = 0.0
    for i in range(nt):
        dep = 0.0
        work = 0.0
        years = 0.0
        for a in range(na):
            d = X[i, a] - xstar[a]
            J += d * d
            if a < 15 or a >= 65:
                dep += X[i, a]
            else:
                work += X[i, a]
            years += X[i, a] * midages[a]
        tot = dep + work
        v = dep - rho0 * work                    # dependency index (8.2-10)
        if v > 0:
            pen += v * v
        v = years / e0[i] - omega0 * tot         # aging index (8.2-11)
        if v > 0:
            pen += v * v
        v = tot - pop_max                        # peak population (8.2-9)
        if v > 0:
            pen += v * v
    return J + pf * pen


@njit(cache=True)
def _objective_and_gradient(beta_in, F0, M0, h, df, dm, tfac, p, mu00, xstar, e0, midages,
                            pf, rho0, omega0, pop_max, lo, hi):
    # Same forward-difference scheme as Song.objective_and_gradient
    n = beta_in.shape[0]
    beta = np.empty(n)
    for j in range(n):
        beta[j] = min(max(beta_in[j], lo), hi)
    f0 = _objective(beta, F0, M0, h, df, dm, tfac, p, mu00, xstar, e0, midages, pf,
                    rho0, omega0, pop_max)
    g = np.empty(n)
    for j in range(n):
        bj = beta[j]
        step = 1.4901161193847656e-08 * max(1.0, abs(bj))
        if bj + step > hi:
            step = -step
        beta[j] = bj + step
        dx = beta[j] - bj
        fj = _objective(beta, F0, M0, h, df, dm, tfac, p, mu00, xstar, e0, midages, pf,
                        rho0, omega0, pop_max)
        beta[j] = bj
        g[j] = (fj - f0) / dx
    return f0, g


def simulate_fast(ctx, beta):
    return _simulate(ctx['F0'], ctx['M0'], np.asarray(beta, float), ctx['h'],
                     ctx['df'], ctx['dm'], ctx['tfac'], ctx['p'], Song.MU00)


def objective_fast(beta, ctx, penalty_factor):
    b = np.clip(np.asarray(beta, float), *Song.BETA_BOUNDS)
    return _objective(b, ctx['F0'], ctx['M0'], ctx['h'], ctx['df'], ctx['dm'],
                      ctx['tfac'], ctx['p'], Song.MU00, XSTAR, ctx['e0'], MIDAGES,
                      float(penalty_factor), Song.SOCIAL_DEPENDENCY_MAX,
                      Song.AGING_INDEX_MAX, Song.POPULATION_MAX)


def objective_and_gradient_fast(beta, ctx, penalty_factor):
    return _objective_and_gradient(np.asarray(beta, float), ctx['F0'], ctx['M0'], ctx['h'],
                                   ctx['df'], ctx['dm'], ctx['tfac'], ctx['p'], Song.MU00,
                                   XSTAR, ctx['e0'], MIDAGES, float(penalty_factor),
                                   Song.SOCIAL_DEPENDENCY_MAX, Song.AGING_INDEX_MAX,
                                   Song.POPULATION_MAX, *Song.BETA_BOUNDS)


def solve_fast(params):
    ctx = build_solve_context(params['initial_pyramid_type'],
                              params['fertility_rate_source'],
                              params['mortality_evolution_factor'],
                              params['newborn_female_proportion'],
                              params['fertility_age_shift_factor'])
    beta = np.full(NT, 2.16)
    for pf in Song.penalty_schedule(params['penalty_factor']):     # continuation, as in Song.py
        res = minimize(objective_and_gradient_fast, beta, jac=True,
                       args=(ctx, pf),
                       method='L-BFGS-B', bounds=[Song.BETA_BOUNDS] * NT,
                       options={'maxiter': params['optimizer_max_iterations'],
                                'ftol': params['optimizer_tolerance']})
        beta = np.clip(res.x, *Song.BETA_BOUNDS)
    X = simulate_fast(ctx, beta)
    return beta, X, ctx


def solve_row(prm):
    """Worker: one optimal-control solve, returns what the main loop stores."""
    beta, X, ctx = solve_fast(prm)
    m = control_metrics(beta, X)
    ratios = Song.dependency_ratio(X)
    omega = Song.aging_index(X, ctx['e0'])
    tot = X.sum(axis=1)
    m['max_dependency_ratio'] = float(ratios.max())
    m['years_dependency_above_bound'] = int((ratios > Song.SOCIAL_DEPENDENCY_MAX + 1e-4).sum())
    m['max_aging_index'] = float(omega.max())
    m['years_aging_above_bound'] = int((omega > Song.AGING_INDEX_MAX + 1e-4).sum())
    m['years_above_1.2B'] = int((tot > Song.POPULATION_MAX * (1 + 1e-6)).sum())
    m['final_year_growth_per_1000'] = float(1000 * (tot[-1] - tot[-2]) / tot[-2])
    m.update({f'param_{k}': v for k, v in prm.items()})
    return m, beta, tot


def verify_against_reference():
    """Fast objective must reproduce Song.objective_function_optimized; the
    finite-difference gradients must agree up to their own rounding noise."""
    worst = 0.0
    worst_g = 0.0
    rng = np.random.default_rng(1)
    for pyr, src_, shift, p, mef, pf in ((0, 0, 0.1, 0.485, 0.05, 1e10), (1, 1, 0.2, 0.47, 0.1, 1e8),
                                         (2, 0, 0.0, 0.5, 0.0, 1e12)):
        ctx = build_solve_context(pyr, src_, mef, p, shift)
        for beta_t in (np.linspace(1.2, 2.16, NT), rng.uniform(1, 2.16, NT), np.full(NT, 2.16)):
            f_fast = objective_fast(beta_t, ctx, pf)
            f_ref = Song.objective_function_optimized(beta_t, ctx['X0'], XSTAR, pf, mef, p,
                                                      Song.fertility_pattern(src_, shift))
            worst = max(worst, abs(f_fast - f_ref) / abs(f_ref))
            g_fast = objective_and_gradient_fast(beta_t, ctx, pf)[1]
            g_ref = Song.objective_and_gradient(beta_t, ctx['X0'], XSTAR, pf, mef, p,
                                                Song.fertility_pattern(src_, shift))[1]
            worst_g = max(worst_g, float(np.max(np.abs(g_fast - g_ref)) / np.max(np.abs(g_ref))))
    return worst, worst_g


def control_metrics(beta, X, last_year=None):
    """Control-path metrics; with last_year, computed on the years up to it
    (the state-side entries always refer to the whole horizon)."""
    if last_year is not None:
        keep = TIME_STEPS <= last_year
        out = control_metrics(beta[keep], X[keep])
        return {k: out[k] for k in ('tfr_min', 'year_tfr_min', 'years_below_2', 'cum_deficit', 'year_return_repl')}
    ts = TIME_STEPS[:len(beta)]
    tot = X.sum(axis=1)
    i_min = int(beta.argmin())
    out = dict(
        tfr_min=float(beta.min()),
        year_tfr_min=int(ts[i_min]),
        years_below_2=int((beta < 2.0).sum()),
        cum_deficit=float(np.clip(2.16 - beta, 0, None).sum()),
        peak_pop=float(tot.max()),
        peak_pop_year=int(ts[tot.argmax()]),
        total_population_2080=float(tot[-1]),
    )
    after = np.where((ts > out['year_tfr_min']) & (beta >= 2.10))[0]
    out['year_return_repl'] = int(ts[after[0]]) if after.size else int(ts[-1])
    return out


