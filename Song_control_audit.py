"""
Song_control_audit.py
---------------------
Re-analysis of the Song et al. optimal-control model with the sensitivity
audit aimed at the model's ACTUAL output: the optimal fertility control path
beta(t), not the constrained state path (total population).

Responds to Caswell's review point: an optimal control problem outputs the
control function; the state path is constrained by construction, so its
invariance is trivially true. The audit therefore asks: how sensitive is the
POLICY PRESCRIPTION (how hard to squeeze fertility, when, for how long) to
the model's uncertain demographic and algorithmic inputs?

Control-path metrics per run:
  tfr_min              lowest fertility the optimiser prescribes
  year_tfr_min         calendar year of the trough
  years_below_2        number of years with prescribed TFR < 2.0
  cum_deficit          sum over years of (2.16 - beta)+  ("TFR-years withheld")
  year_return_repl     first year after the trough with beta >= 2.10
  peak_pop_year        year of maximum total population (state side, for figure)
  peak_pop             maximum total population

Design used in the paper: SALTELLI_N=512 (Saltelli design, N(k+2) = 5,120
solves). Without SALTELLI_N the script runs a plain scrambled Sobol' design
(N_SIM runs), kept as a quick check only.
Sensitivity: first-order and total-order Sobol' indices (Saltelli mode),
given-data optimal-transport indices (Wasserstein-2^2 normalised by 2 Var(Y),
one class per level for discrete inputs) and a given-data first-order index
on the same partition.

The model is a verified fast reimplementation of the functions in Song.py
(same arithmetic, compiled with numba). The objective is checked against
Song.objective_function_optimized at startup, for several input settings, and
the script aborts on mismatch.

Revised Nov 2026 (see CHANGELOG.md) to follow Song, Tuan and Yu (1985),
Population Control in China, chapter 8, as closely as the book allows: the
three state constraints of Program 1 (peak population at most 1.2 billion,
dependency index at most 1, aging index = mean age / life expectancy at
most 0.7), the target X* = stationary population of 700 million implied by
the model's mortality (8.2-1 to 8.2-3), the performance index (8.4-2) with
every age counted once, the infants of year t generated by beta(t) as in
(2.2-13), and the book's Tables 2.5 and 6.1 transcribed afresh. Also: the
fertility pattern is normalised (beta = TFR), the age shift moves
childbearing older, death rates are step functions of age, the projection
is two-sex, and the observed China series is read from WPP 2024.

Runs are spread over WORKERS processes (default: all cores). Rows are written
in sample order every few runs, so an interrupted run resumes with RESUME=1.
"""

